# frozen_string_literal: true

# Generates lib/common/map/map_crossings.rb from the StringProcs that neither
# the recognizers nor the manual schema cover: each remaining proc body is
# relocated VERBATIM into a named block in reviewed Lich code, and a matching
# {"strategy" => "unique_crossing", "name" => ...} entry is merged into the
# manual conversions file. The code is moved, not rewritten - no semantic
# drift - and the mapdb keeps only the name.
#
#   ruby tools/gen_crossings.rb --in MAP.json
#
# Regenerate whenever a new one-off proc appears; refactor individual
# crossings into proper strategies at leisure.

require 'json'
require 'optparse'
require_relative 'mapdb_convert'

options = {}
OptionParser.new do |opts|
  opts.on('--in FILE') { |v| options[:in] = v }
end.parse!
abort 'missing --in' unless options[:in]

manual_path = File.expand_path('mapdb_manual_conversions.json', __dir__)
crossings_path = File.expand_path('../lib/common/map/map_crossings.rb', __dir__)

converter = MapdbConverter.new
converter.load_manual(manual_path)
map = JSON.parse(File.read(options[:in]))

bodies = {} # body => [edge keys]
map.each do |room|
  (room['wayto'] || {}).each do |dest, value|
    next unless value.is_a?(String) && value.start_with?(';e ')
    body = value[3..]
    next if converter.convert_wayto(body) || converter.manual_for('wayto', room['id'], dest)
    (bodies[body] ||= []) << "#{room['id']}:#{dest}"
  end
end

manual = JSON.parse(File.read(manual_path))
defs = +''
bodies.each do |body, edges|
  name = "crossing_#{edges.first.sub(':', '_')}"
  edges.each { |key| manual['wayto'][key] = { 'strategy' => 'unique_crossing', 'name' => name } }
  defs << "\n        define('#{name}') do # #{edges.join(' ')}\n"
  defs << body.gsub(/^/, '          ').rstrip
  defs << "\n        end\n"
end

File.write(crossings_path, <<~'HEADER' + defs + <<~'FOOTER')
  # frozen_string_literal: true

  # rubocop:disable all
  # One-off travel crossings relocated verbatim from mapdb StringProcs.
  #
  # GENERATED by tools/gen_crossings.rb - each block below is the exact Ruby
  # a map edge used to carry as an eval'd string. Living here it is reviewed,
  # diffable Lich code; the mapdb references it by name via
  #   { "strategy" => "unique_crossing", "name" => "crossing_ROOM_DEST" }
  # Refactor blocks into proper strategies at leisure; regenerate when a new
  # one-off proc appears in an unconverted map.

  module Lich
    module Common
      module MapEngine
        module UniqueCrossings
          REGISTRY = {}

          def self.define(name, &block)
            REGISTRY[name.to_s] = block
          end

          def self.known?(name)
            REGISTRY.key?(name.to_s)
          end

          def self.run(name)
            block = REGISTRY[name.to_s]
            raise StepFailed, "unknown crossing #{name.inspect}" unless block
            block.call
            true
          end
HEADER
        end
      end
    end
  end
  # rubocop:enable all
FOOTER

File.write(manual_path, JSON.pretty_generate(manual))
puts "wrote #{bodies.size} crossings (#{bodies.values.sum(&:size)} edges) to map_crossings.rb; manual file updated"
